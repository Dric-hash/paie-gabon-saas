/**
 * Applique les traductions sur toute la page.
 * Cherche tous les éléments avec data-i18n et remplace leur texte.
 */
function applyTranslations(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['fr'];
  const rtl  = lang === 'ar';

  // Appliquer direction RTL/LTR
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', rtl ? 'rtl' : 'ltr');
  if (rtl) {
    document.documentElement.style.fontFamily = "'Cairo', Arial, sans-serif";
  }

  // Traduire les éléments data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });

  // Traduire les placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.setAttribute('placeholder', dict[key]);
  });

  // Traduire les titles (tooltips)
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dict[key]) el.setAttribute('title', dict[key]);
  });
}

// Lire la langue depuis le cookie ou le localStorage
function getCurrentLang() {
  return localStorage.getItem('pg_lang') ||
         document.documentElement.getAttribute('lang') ||
         'fr';
}

// Appliquer au chargement
document.addEventListener('DOMContentLoaded', () => {
  const lang = getCurrentLang();
  if (lang !== 'fr') applyTranslations(lang);
});
